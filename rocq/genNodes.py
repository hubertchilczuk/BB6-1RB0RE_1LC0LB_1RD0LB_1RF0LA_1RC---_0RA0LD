"""Generate rocq/N/Nodes.v: the node forms off_<tag>_<par> of all nodes used by the proof (lemma-A nodes, lemma-B
start nodes and targets), and rocq/N/nodes.json: for every form its name, the names to unfold, the argument count.
usage: genNodes.py
"""
import os, sys, json
import rocqgen as RG
import nodeform as NF

OUT = RG.ROOT + 'rocq/N/'
os.makedirs(OUT, exist_ok=True)


def needed_nodes():
    keys = set(json.load(open(RG.ROOT + 'rocq/anodes.json')))
    for bkey, B in NF.P['lemmaB'].items():
        keys.add(bkey.split(' ## ')[0]); keys.add(B['target'])
    for key, ni in NF.P['nodes'].items():
        if 'P' in ni: keys.add(key)
    return sorted(k for k in keys if k in NF.S)


if __name__ == '__main__':
    keys = needed_nodes()
    v = ['(* generated by rocq/genNodes.py: node forms off_<tag>_<parity of M> *)',
         'From BusyCoq Require Import Individual62.', 'Open Scope list.', '']
    index, fails = {}, []
    for key in keys:
        node = NF.Node(key)
        for par in (0, 1):
            try:
                toks, vals = node.form(par)
            except Exception as e:
                fails.append((key[:70], par, repr(e))); continue
            names = RG.Names('N%s%d_' % (node.tag, par))
            nv = sum(1 for t in toks if t[0] == 'var')
            args = {t[1]: 'z%d' % i for i, t in enumerate(t for t in toks if t[0] == 'var')}
            body = RG.render(toks, args, names)
            v.append('(* %s, M parity %d *)' % (key.replace('*)', '* )'), par))
            v += names.defs()
            v.append('Definition %s %s : Q * tape := 0inf {{C}}> %s.' % (node.name(par), ' '.join('z%d' % i for i in range(nv)), body))
            v.append('')
            index[node.name(par)] = {'key': key, 'par': par, 'unfold': [node.name(par)] + names.all(), 'nargs': nv}
    open(OUT + 'Nodes.v', 'w').write('\n'.join(v) + '\n')
    json.dump(index, open(OUT + 'nodes.json', 'w'), indent=1)
    print('nodes %d, forms %d, failures %d' % (len(keys), len(index), len(fails)))
    for f in fails[:10]: print('  ', f)

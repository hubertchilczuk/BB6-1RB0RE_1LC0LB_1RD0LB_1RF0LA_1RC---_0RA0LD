"""Generate a Rocq proof of lemma A for one node, split into sub-lemmas between sweep checkpoints.

Lemma A:  0inf {{C}}> Z *> w^(P+n) *> T *> u^m *> tail  -->+  0inf {{C}}> Z *> w^n *> T *> u^(m+dM) *> tail
for ALL n, m (no lower bounds needed).

Checkpoints: the configurations at every G-th "new leftmost cell" event (head at the left end, state C).
They are found by plain simulation of two concrete instances; at every checkpoint the tape must be
    prefix_i *> w^(e_i + n) *> T *> u^(d_i + m) *> tail
with prefix_i, e_i, d_i the same for both instances. Sub-lemma i (proved by ES_v3 `es'`):
    cfg prefix_i e_i n m  -->+  cfg' prefix_{i+1} e_{i+1} n m (d_{i+1} - d_i new pairs after u^^m)
usage: gen_lemmaA.py OUT.v [G] [MAXSUB]
"""
import os, sys, json, subprocess
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__))) + '/'
sys.path.insert(0, ROOT)
import gen2

EVT = ROOT + 'an/evtapes.exe'
TMP = ROOT + 'rocq/tmp/'
os.makedirs(TMP, exist_ok=True)
P = json.load(open(ROOT + 'proof4.json'))
NODE = next(k for k in P['lemmaA'] if k.startswith('1 7 0 0* 4 3 0 0 0 0 0 9 | 8  || 3 / 0 1 / 0 / 6542ed25be'))
st = gen2.parse(ROOT + 's_226258280.txt', '1 7 0 0* 4 3 0 0 0 0 0 9 | 8 ')
Pp, dM = P['nodes'][NODE]['P'], P['nodes'][NODE]['dM']
Z, w, T, u, tail = st['zone_cells'], st['w_cells'], st['T_cells'], st['u_cells'], st['tail_cells'].rstrip('0')


def checkpoints(n, m):
    cfg = TMP + 'inst_%d_%d.txt' % (n, m)
    open(cfg, 'w').write('0 2 0\n%s\n' % (Z + w * (Pp + n) + T + u * m + tail))
    target = Z + w * n + T + u * (m + dM) + tail
    out = subprocess.run([EVT, cfg, '1000000000', '100000'], capture_output=True, text=True).stdout.split('\n')
    cps = []
    for i in range(0, len(out) - 1, 2):
        step, state = map(int, out[i].split())
        tape = out[i + 1]
        assert state == 2, 'checkpoint not in state C'
        cps.append((step,) + split(tape, n, m))
        if tape == target: return cps
    raise RuntimeError('target not reached')


def split(tape, n, m):
    """tape = prefix + w^(e+n) + T + u^(d+m) + tail (greedy from the right) -> (prefix, e, d)"""
    assert tape.endswith(tail)
    rest = tape[:len(tape) - len(tail)]
    uc = 0
    while rest.endswith(u): rest = rest[:-len(u)]; uc += 1
    assert rest.endswith(T), 'T not found'
    rest = rest[:-len(T)]
    wc = 0
    while rest.endswith(w): rest = rest[:-len(w)]; wc += 1
    return rest, wc - n, uc - m


def lit(cells):
    return '[' + ';'.join(cells) + ']'


def side(prefix, e, d):
    """right side from the head: prefix *> w^e *> w^^n *> T *> u^^m *> u^d *> tail *> 0inf"""
    parts = [lit(prefix + w * e), '(w^^n)', lit(T), '(u^^m)']
    if d: parts.append(lit(u * d))
    if tail: parts.append(lit(tail))
    return ' *> '.join(parts) + ' *> 0inf'


if __name__ == '__main__':
    out = sys.argv[1]
    G = int(sys.argv[2]) if len(sys.argv) > 2 else 25
    MAXSUB = int(sys.argv[3]) if len(sys.argv) > 3 else 10 ** 9
    a, b = checkpoints(7, 11), checkpoints(12, 19)
    assert len(a) == len(b), (len(a), len(b))
    for x, y in zip(a, b): assert x[1:] == y[1:], 'checkpoint depends on n, m'
    cps = [(0,) + split(Z + w * (Pp + 7) + T + u * 11 + tail, 7, 11)] + [a[i] for i in range(G - 1, len(a) - 1, G)] + [a[-1]]
    assert cps[-1][1] + w * cps[-1][2] == cps[0][1] + w * (cps[0][2] - Pp) and cps[-1][3] - cps[0][3] == dM
    for x, y in zip(cps, cps[1:]): assert y[3] >= x[3] and y[2] <= x[2]
    nsub = min(MAXSUB, len(cps) - 1)
    v = ['(* generated by rocq/gen_lemmaA.py: lemma A of the start node, P = %d, dM = %d, %d events, %d sub-lemmas *)' % (Pp, dM, len(a), nsub),
         'From BusyCoq Require Import Individual62 ES_v3.',
         'Require Import Lia String NArith.',
         'Open Scope list.', '',
         'Definition tm := Eval compute in (TM_from_str "1RB0RE_1LC0LB_1RD0LB_1RF0LA_1RC---_0RA0LD").',
         """Notation "c -->+ c'" := (c -[ tm ]->+ c') (at level 40).""", '',
         'Definition w : list sym := %s.' % lit(w),
         'Definition u : list sym := %s.' % lit(u),
         'Definition T : list sym := %s.' % lit(T),
         'Definition tl : list sym := %s.' % lit(tail), '',
         'Lemma u_add m d r : (u^^(m+d)) *> r = (u^^m) *> (u^^d) *> r.',
         'Proof. rewrite lpow_add, Str_app_assoc. reflexivity. Qed.', '']
    for i in range(nsub + 1):
        p_, e_, d_ = cps[i][1:]
        v.append('Definition cfg%d n m : Q * tape := 0inf {{C}}> %s *> (w^^n) *> T *> (u^^m) *> tl *> 0inf.' % (i, lit(p_ + w * e_)))
    v.append('')
    deltas = []
    for i in range(nsub):
        dlt = cps[i + 1][3] - cps[i][3]; deltas.append(dlt)
        v += ['Lemma sub%d n m : cfg%d n m -->+ cfg%d n (m + %d).' % (i, i, i + 1, dlt),
              "Proof. unfold cfg%d, cfg%d. rewrite u_add. unfold w, u, T, tl. cbn [lpow app]. es' n m. Qed." % (i, i + 1), '']
    if nsub == len(cps) - 1:
        v += ['Theorem lemmaA n m : cfg0 n m -->+ cfg%d n (m + %d).' % (nsub, dM),
              'Proof.',
              '  replace (m + %d) with (m%s) by lia.' % (dM, ''.join(' + %d' % x for x in deltas))]
        acc = 'm'
        for i in range(nsub - 1):
            v.append('  eapply progress_trans; [apply (sub%d n (%s))|].' % (i, acc))
            acc = '%s + %d' % (acc, deltas[i])
        v += ['  apply (sub%d n (%s)).' % (nsub - 1, acc), 'Qed.', '',
              '(* cfg0 = Z *> w^P *> w^^n ..., cfg%d = Z *> w^^n ... as cell lists *)' % nsub,
              'Lemma cfg0_eq n m : cfg0 n m = 0inf {{C}}> %s *> (w^^n) *> T *> (u^^m) *> tl *> 0inf.' % lit(Z + w * Pp),
              'Proof. reflexivity. Qed.',
              'Lemma cfgF_eq n m : cfg%d n m = 0inf {{C}}> %s *> (w^^n) *> T *> (u^^m) *> tl *> 0inf.' % (nsub, lit(Z)),
              'Proof. reflexivity. Qed.']
    open(out, 'w').write('\n'.join(v) + '\n')
    print('events %d, checkpoints %d, sub-lemmas written %d, file %d bytes' % (len(a), len(cps), nsub, sum(map(len, v))))

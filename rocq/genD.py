"""Descent lemmas: iterate lemma A by induction (rocq/D/D_<tag>_<par>.v, requires rocq/A2/A_<tag>_<par>.v).

    F_<tag>_<par> N h [y] := off_<tag>_<par> (run values at N, M = par + 2h, k = kp + 2y)
    descent q N h [y] : N >= NB -> h >= HB [-> y >= YB] -> F (N + P*q) h [y] -->* F N (h + D*q) [y]     (D = dM/2)

usage: genD.py [node-index ...]
"""
import os, sys, json, re
import rocqgen as RG
import nodeform as NF
from genA2 import NB, HB, YB

OUT = RG.ROOT + 'rocq/D/'
os.makedirs(OUT, exist_ok=True)


def top_args(side):
    """'off_x (a + n) (h) ...' -> ['a + n', 'h', ...]"""
    out, depth, cur = [], 0, ''
    for ch in side:
        if ch == '(':
            if depth: cur += ch
            depth += 1
        elif ch == ')':
            depth -= 1
            if depth: cur += ch
            else: out.append(cur); cur = ''
        elif depth: cur += ch
    return out


def expr(const, coef, names):
    terms = []
    for c, nm in zip(coef, names):
        if c: terms.append(nm if c == 1 else '%d * %s' % (c, nm))
    s = ' + '.join(terms) or '0'
    return '%s + %d' % (s, const) if const > 0 else ('%s - %d' % (s, -const) if const < 0 else s)


def generate(key, par):
    node = NF.Node(key)
    tag = node.tag
    afile = RG.ROOT + 'rocq/A2/A_%s_%d.v' % (tag, par)
    th = next(l for l in open(afile) if l.startswith('Theorem lemmaA'))
    head, sides = th.split(':', 1)
    lhs, rhs = sides.rstrip().rstrip('.').split('-->+')
    la, ra = top_args(lhs), top_args(rhs)
    sym_k = node.family_key
    pn = ('n', 'h', 'y') if sym_k else ('n', 'h')
    toks, vals = node.form(par)
    fargs = [expr(*vals[t[1]], ('N', 'h', 'y')) for t in toks if t[0] == 'var']
    # params of F: N, h and (k-structure) y; non-family k-structure nodes have y fixed (their k)
    Fp = 'N h y' if node.fam else 'N h'
    yfix = None
    if node.fam and not sym_k:
        yfix = (node.kfix - node.kp) // 2
    Pp, D = node.P, node.dM // 2
    off = node.name(par)
    sub = {'n': '(N + %d * q - %d)' % (Pp, NB), 'h': '(h - %d)' % HB, 'y': '(y - %d)' % YB}
    inst = lambda a: re.sub(r'\b([nhy])\b', lambda m: sub[m.group(1)], a)
    F = 'F_%s_%d' % (tag, par)
    yv = ' y' if node.fam else ''
    hyps = 'N >= %d -> h >= %d%s' % (NB, HB, ' -> y >= %d' % YB if sym_k else (' -> y = %d' % yfix if node.fam else ''))
    v = ['(* generated by rocq/genD.py: descent of node', '   %s, M parity %d *)' % (key.replace('*)', '* )'), par),
         'From BusyCoq Require Import Individual62 ES_v3.', 'From BB6N Require Import Nodes.', 'From BB6F Require Import F.', 'Require Import Lia.',
         'Require A_%s_%d.' % (tag, par), 'Open Scope list.', '',
         'Definition tm := A_%s_%d.tm.' % (tag, par),
         """Notation "c -->+ c'" := (c -[ tm ]->+ c') (at level 40).""",
         """Notation "c -->* c'" := (c -[ tm ]->* c') (at level 40).""", '',
         'Lemma %s_step q N h%s : %s -> %s (N + %d * S q) h%s -->+ %s (N + %d * q) (h + %d)%s.' % (F, yv, hyps, F, Pp, yv, F, Pp, D, yv),
         'Proof.',
         '  intros HN Hh%s.' % (' Hy' if node.fam else ''),
         '  eapply (A_%s_%d.last_eq _ (%s %s) (%s %s)).' % (tag, par, off, ' '.join('(%s)' % inst(a) for a in la), off, ' '.join('(%s)' % inst(a) for a in ra)),
         '  - unfold %s. f_equal; lia.' % F,
         '  - apply (A_%s_%d.lemmaA %s).' % (tag, par, ' '.join(sub[p] for p in pn)),
         '  - unfold %s. f_equal; lia.' % F,
         'Qed.', '',
         'Theorem %s_descent q : forall N h%s, %s -> %s (N + %d * q) h%s -->* %s N (h + %d * q)%s.' % (F, yv, hyps, F, Pp, yv, F, D, yv),
         'Proof.',
         '  induction q as [|q IH]; intros N h%s HN Hh%s.' % (yv, ' Hy' if node.fam else ''),
         '  - replace (N + %d * 0) with N by lia. replace (h + %d * 0) with h by lia. apply evstep_refl.' % (Pp, D),
         '  - eapply evstep_trans; [apply progress_evstep, %s_step; lia |].' % F,
         '    replace (h + %d * S q) with (h + %d + %d * q) by lia. apply IH; lia.' % (D, D, D),
         'Qed.']
    if node.fam and not sym_k:
        pass
    open(OUT + 'D_%s_%d.v' % (tag, par), 'w').write('\n'.join(v) + '\n')


if __name__ == '__main__':
    keys = json.load(open(RG.ROOT + 'rocq/anodes.json'))
    idx = [int(a) for a in sys.argv[1:]] or range(len(keys))
    for i in idx:
        for par in (0, 1):
            try: generate(keys[i], par)
            except Exception as e: print('FAIL', i, par, repr(e))

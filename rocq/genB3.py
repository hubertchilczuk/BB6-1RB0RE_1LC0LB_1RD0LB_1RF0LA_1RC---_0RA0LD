"""Lemma B in the canonical node representation (rocqgen + nodeform).

    lemmaB x [y] : node form of (node, N = r, M = M0 + 2x[, k = Kd + 2y])  -->+  node form of (target, N1, M1[, K1])

M0 = smallest domain M (>= 500) with the lemma's parity; for family source nodes Kd = smallest domain k (K_fam with
the family's parity). Checkpoints every G sweeps from instances on a design over (x[, y]); the first/last checkpoint
use the node masks of the source / target node.
usage: genB3.py "<lemma-B key>" OUT.v [G]
"""
import sys, json
import rocqgen as RG
import nodeform as NF

NODES = json.load(open(RG.ROOT + 'rocq/N/nodes.json'))
HEADER = RG.HEADER[:1] + ['From BB6N Require Import Nodes.'] + RG.HEADER[1:]


def same_form(pieces, mask, node, par):
    """the canonical rendering of a checkpoint equals the node form (literal cells, unit blocks, variable positions)"""
    t1 = RG.canon(pieces, mask)[0]; t2 = node.form(par)[0]
    if t1 != t2: raise ValueError('checkpoint is not in the node form of %s' % node.key[:60])

MSTAR = 500
M0_, K0_ = 1000, 1000     # base values of the proof's lemma variables: x' = (M - M0_ - par)/2, y' = (k - K0_ - park)/2


def generate(bkey, outfile, G=200, start=None):
    """start: a partial node (concrete k) that uses the family's lemma-B record bkey"""
    node = NF.Node(start or bkey.split(' ## ')[0])
    r = int(bkey.split('r=')[1].split()[0]); par = int(bkey.split('par=')[1])
    B = NF.P['lemmaB'][bkey]; tgt = NF.Node(B['target'])
    M0 = MSTAR + ((par - MSTAR) % 2)
    yfix = 0
    if start:
        fam = bkey.split(' ## ')[0]
        yfix = (node.kfix - K0_ - int(fam.split('park=')[1][0])) // 2
    if node.family_key:
        park = int(node.key.split('park=')[1][0])
        kf = NF.P['nodes'][node.key]['K_fam']
        Kd = kf + ((park - kf) % 2)
        # partial nodes of this family use this record for their states outside concrete_states: cover their k too
        for pk, pi in NF.P['nodes'].items():
            if pi.get('partial_of') == node.key and [r, par] not in pi.get('concrete_states', []):
                Kd = min(Kd, pi['k'])
        design = [(50, 0), (100, 0), (50, 3), (150, 6)]
        pnames = ('x', 'y')
    else:
        park, Kd = 0, None
        design = [(50,), (100,), (150,)]
        pnames = ('x',)
    runs, starts, ends = [], [], []
    for row in design:
        x = row[0]; M = M0 + 2 * x
        k = Kd + 2 * row[1] if node.family_key else None
        xx = (M - M0_ - par) // 2
        yy = (k - K0_ - park) // 2 if node.family_key else yfix
        ev = lambda c: None if c is None else c[0] + c[1] * xx + c[2] * yy
        n1, m1, k1 = ev(B['N1']), ev(B['M1']), ev(B['K1'])
        start = node.tape(r, M, k)
        end = tgt.tape(n1, m1, k1 if tgt.family_key else None)
        starts.append(start); ends.append(end)
        runs.append(RG.run_to(start, end, G))
    if len({len(c) for c in runs}) != 1: raise ValueError('checkpoint counts differ')
    if any(c[-1] != e for c, e in zip(runs, ends)): raise RuntimeError('last checkpoint is not the target')
    cps = [RG.family(starts, design)] + [RG.family([c[i] for c in runs], design) for i in range(len(runs[0]))]
    par1 = B['M1'][0] % 2        # parity of M1 (its x and y coefficients are even)
    masks = [node.check_skeleton(cps[0], par)] + [[RG.is_var(p) for p in c] for c in cps[1:-1]] + [tgt.check_skeleton(cps[-1], par1)]
    same_form(cps[0], masks[0], node, par); same_form(cps[-1], masks[-1], tgt, par1)
    names = RG.Names()
    e0, e1 = node.name(par), tgt.name(par1)
    body, vals, vl = RG.chain(cps, masks, pnames, 'lemmaB', names, ends={0: e0, len(cps) - 1: e1},
                              extra_unfold=sorted(set(NODES[e0]['unfold'] + NODES[e1]['unfold'])))
    v = ['(* generated by rocq/genB3.py: lemma B', '   %s' % bkey.replace('*)', '* )'),
         '   target %s' % tgt.key.replace('*)', '* )'),
         '   M = %d + 2x%s, %d checkpoints *)' % (M0, ', k = %d + 2y' % Kd if node.family_key else '', len(cps))] + HEADER + names.defs() + [''] + body
    text = '\n'.join(v).replace('@@NAMES@@', ', '.join(names.all()) or 'tm')
    open(outfile, 'w').write(text + '\n')
    return len(cps)


if __name__ == '__main__':
    print('checkpoints', generate(sys.argv[1], sys.argv[2], int(sys.argv[3]) if len(sys.argv) > 3 else 200))

"""Generate rocq/C/Final.v: the main theorem

    nonhalt : ~ halts (TM_from_str "1RB0RE_1LC0LB_1RD0LB_1RF0LA_1RC---_0RA0LD") c0

  * closure : every Dom state has a successor in Dom (-->+), one case per Dom constructor (Close_*.v);
  * start   : c0 -->* F_start 224 1022 (Start.v), then two lemma-A steps (descent) to F_start 24 (1022 + 2*872),
              a Dom state (r = 24, M = 1 + 2*2766 = 5533);
  * progress_nonhalt (busycoq TM.v) and multistep_nonhalt.
usage: genFinal.py
"""
import json, re
import rocqgen as RG

OUT = RG.ROOT + 'rocq/C/'
MACHINE = '1RB0RE_1LC0LB_1RD0LB_1RF0LA_1RC---_0RA0LD'
START, PAR, P, D = '60462068', 1, 100, 872

ctors = []
for line in open(RG.ROOT + 'rocq/F/Dom.v'):
    m = re.match(r'\s*\| (\S+) ', line)
    if m: ctors.append(m.group(1))
mods = ['Close_%s' % (c[4:] if c.startswith('dom_') else c) for c in ctors]
v = ['(* generated by rocq/genFinal.py: the machine does not halt *)',
     'From BusyCoq Require Import Individual62.', 'From BB6N Require Import Nodes.', 'From BB6F Require Import F Dom.',
     'Require Import Lia String.', 'Require Start D_%s_%d.' % (START, PAR)] + ['Require %s.' % m for m in mods] + [
     'Open Scope list.', '',
     'Definition tm := TM_from_str "%s".' % MACHINE, '',
     'Lemma closure c : Dom c -> exists c\', Dom c\' /\\ c -[ tm ]->+ c\'.',
     'Proof.',
     '  intros H. destruct H.']
for c, m in zip(ctors, mods):
    v.append('  - eapply %s.close_%s; eassumption.' % (m, c))
v += ['Qed.', '',
      'Theorem nonhalt : ~ halts tm c0.',
      'Proof.',
      '  apply (multistep_nonhalt _ _ (F_%s_%d 24 (1022 + %d * 2))).' % (START, PAR, D),
      '  - eapply evstep_trans; [exact Start.start |].',
      '    change (off_%s_%d 223 1022) with (F_%s_%d (24 + %d * 2) 1022).' % (START, PAR, START, PAR, P),
      '    apply D_%s_%d.F_%s_%d_descent; lia.' % (START, PAR, START, PAR),
      '  - apply (progress_nonhalt _ Dom); [exact closure |].',
      '    apply dom_%s_%d; lia.' % (START, PAR),
      'Qed.']
open(OUT + 'Final.v', 'w').write('\n'.join(v) + '\n')
# separate file: loading Final already needs ~12 GB, and Print Assumptions also forces every opaque proof body
open(OUT + 'Assumptions.v', 'w').write('Require Final.\nPrint Assumptions Final.nonhalt.\n')
print('Final.v: %d Dom constructors' % len(ctors))

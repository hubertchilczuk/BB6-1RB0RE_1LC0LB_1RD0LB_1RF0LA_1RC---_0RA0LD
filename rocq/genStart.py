"""Generate rocq/S/Start.v: the blank tape reaches the start configuration (step 226258281) of the proof:

    start : c0 -[ tm ]->* off_<start>_1 (values of N = 224, M = 2045)

by a verified concrete simulator: cconfig_step (busycoq Individual62) iterated with N.iter (binary fuel).
All comparisons of the 25k-cell tapes are boolean (cconfig_eqb / cside_eqb) computed by vm_compute, so the
kernel never compares the long lists structurally.
usage: genStart.py
"""
import os
import rocqgen as RG
import nodeform as NF

OUT = RG.ROOT + 'rocq/S/'
os.makedirs(OUT, exist_ok=True)
STEPS = 226258281
CH = 1000

st = open(RG.ROOT + 's_226258280.txt').read().split()
assert int(st[0]) == STEPS and int(st[1]) == 2 and int(st[2]) == 0
cells = st[3].rstrip('0')
node = NF.Node(next(k for k in NF.P['lemmaA'] if k.startswith('1 7 0 0* 4 3 0 0 0 0 0 9 | 8  || 3 / 0 1 / 0 / 6542ed25be')))
par, N, M = 1, 224, 2045
assert node.tape(N, M) == cells, 'start sample differs from the node tape'
args = node.values(par, N, (M - par) // 2)
off = '%s %s' % (node.name(par), ' '.join('(%d)' % a for a in args))
rest = cells[1:]
nch = (len(rest) + CH - 1) // CH
v = ['(* generated by rocq/genStart.py: the blank tape reaches the start configuration of the proof *)',
     'From BusyCoq Require Import Individual62.', 'From BB6N Require Import Nodes.', 'Require Import NArith Lia String.', 'Open Scope list.', '',
     'Definition tm := Eval compute in (TM_from_str "1RB0RE_1LC0LB_1RD0LB_1RF0LA_1RC---_0RA0LD").', '',
     '(* iterate cconfig_step with binary fuel *)',
     'Definition step_opt (o : option cconfig) : option cconfig :=',
     '  match o with Some x => cconfig_step tm x | None => None end.',
     'Definition run (n : N) (x : cconfig) : option cconfig := N.iter n step_opt (Some x).', '',
     'Lemma run_spec n : forall x y, run n x = Some y -> cconfig_to_config x -[ tm ]->* cconfig_to_config y.',
     'Proof.',
     '  induction n using N.peano_ind; intros x y H; unfold run in *.',
     '  - cbn in H. inversion H. apply evstep_refl.',
     '  - rewrite N.iter_succ in H.',
     '    destruct (N.iter n step_opt (Some x)) as [z|] eqn:E; [|discriminate].',
     '    cbn in H. pose proof (cconfig_step_spec tm z) as Hs. rewrite H in Hs.',
     '    eapply evstep_trans; [apply IHn, E|]. eapply evstep_step; [exact Hs | apply evstep_refl].',
     'Qed.', ''] + \
    ['Definition R0_%d : list Sym := %s.' % (i, RG.lit(rest[i * CH:(i + 1) * CH])) for i in range(nch)] + [
     'Definition R0 : list Sym := %s.' % ' ++ '.join('R0_%d' % i for i in range(nch)),
     'Definition cstart : cconfig := (nil, R0, %s, C).' % cells[0], '',
     '(* the check is stated inline: wrapping it in a Definition made the VM run out of memory *)',
     'Lemma reach_ok : (match run (%d%%N) (nil, nil, 0, A) with Some y => cconfig_eqb y cstart | None => false end) = true.' % STEPS,
     'Proof. vm_compute. reflexivity. Time Qed.', '',
     'Lemma reach : c0 -[ tm ]->* cconfig_to_config cstart.',
     'Proof.',
     '  pose proof reach_ok as H.',
     '  destruct (run (%d%%N) (nil, nil, 0, A)) as [y|] eqn:E; [|discriminate].' % STEPS,
     '  rewrite c0_to_cconfig, <- (cconfig_eqb_spec _ _ H). exact (run_spec _ _ _ E).',
     'Qed.', '',
     'Lemma cfg_of_list (l : list Sym) (m : Sym) (q : Q) : cconfig_to_config (nil, l, m, q) = 0inf {{q}}> ((m :: l) *> 0inf).',
     'Proof. reflexivity. Qed.', '',
     'Lemma start_eq : cconfig_to_config cstart = %s.' % off,
     'Proof.',
     '  unfold cstart. rewrite cfg_of_list. unfold %s. repeat rewrite <- Str_app_assoc.' % node.name(par),
     '  apply (f_equal (fun s => 0inf {{C}}> s)).',
     '  apply cside_eqb_spec. vm_compute. reflexivity.',
     'Qed.', '',
     'Theorem start : c0 -[ tm ]->* %s.' % off,
     'Proof. rewrite <- start_eq. exact reach. Qed.']
open(OUT + 'Start.v', 'w').write('\n'.join(v) + '\n')
print('Start.v written; start args', args)

"""Lemma A in the canonical node representation (rocqgen + nodeform), one file per (node, parity of M).

    lemmaA n h [y] : off(N = NB + P + n, M = par + 2(HB + h)[, k = kp + 2(YB + y)])
                -->+ off(N = NB + n,     M + dM,               [k])

(off = the node form off_<tag>_<par>; NB = 12 = r_low, HB = YB = 1 keep the argument constants nonnegative.)
usage: genA2.py "<node key>" PAR OUT.v [G]
"""
import sys, json
import rocqgen as RG
import nodeform as NF
from genB3 import NODES, HEADER, same_form

NB, HB, YB = 12, 1, 1


def generate(key, par, outfile, G=100):
    node = NF.Node(key)
    Pp, dM = node.P, node.dM
    assert dM % 2 == 0
    sym_k = node.family_key
    design = [(7, 11, 5), (14, 11, 5), (7, 22, 5), (7, 11, 11), (9, 14, 7)] if sym_k else [(7, 11), (14, 11), (7, 22), (9, 14)]
    pnames = ('n', 'h', 'y') if sym_k else ('n', 'h')
    runs, starts, ends = [], [], []
    for row in design:
        n, h = row[0], row[1]
        y = YB + row[2] if sym_k else None
        start = node.tape_p(par, NB + Pp + n, HB + h, y)
        end = node.tape_p(par, NB + n, HB + h + dM // 2, y)
        starts.append(start); ends.append(end)
        runs.append(RG.run_to(start, end, G))
    if len({len(c) for c in runs}) != 1: raise ValueError('checkpoint counts differ')
    if any(c[-1] != e for c, e in zip(runs, ends)): raise RuntimeError('last checkpoint is not the target')
    cps = [RG.family(starts, design)] + [RG.family([c[i] for c in runs], design) for i in range(len(runs[0]))]
    masks = [node.check_skeleton(cps[0], par)] + [[RG.is_var(p) for p in c] for c in cps[1:-1]] + [node.check_skeleton(cps[-1], par)]
    same_form(cps[0], masks[0], node, par); same_form(cps[-1], masks[-1], node, par)
    names = RG.Names()
    e = node.name(par)
    body, vals, vl = RG.chain(cps, masks, pnames, 'lemmaA', names, ends={0: e, len(cps) - 1: e},
                              extra_unfold=NODES[e]['unfold'])
    v = ['(* generated by rocq/genA2.py: lemma A of node', '   %s' % key.replace('*)', '* )'),
         '   M parity %d, P = %d, dM = %d, N = %d + P + n, M = %d + 2(%d + h)%s, %d checkpoints *)'
         % (par, Pp, dM, NB, par, HB, ', k = %d + 2(%d + y)' % (node.kp, YB) if sym_k else '', len(cps))] + HEADER + names.defs() + [''] + body
    text = '\n'.join(v).replace('@@NAMES@@', ', '.join(names.all()) or 'tm')
    open(outfile, 'w').write(text + '\n')
    return len(cps)


if __name__ == '__main__':
    print('checkpoints', generate(sys.argv[1], int(sys.argv[2]), sys.argv[3], int(sys.argv[4]) if len(sys.argv) > 4 else 100))

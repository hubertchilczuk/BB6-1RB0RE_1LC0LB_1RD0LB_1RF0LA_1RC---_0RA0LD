"""Generate rocq/F/F.v (node configurations in natural parameters) and rocq/F/Dom.v (the domain of the induction).

    F_<tag>_<par> N h [y] := off_<tag>_<par> (run values)        M = par + 2h, k = kp + 2y (nodes with the k-structure)

    Dom: one constructor per reachable node and parity:
      families:            12 <= r < 12 + P -> 250 <= h -> YF <= y -> Dom (F r h y)        (k >= K_fam)
      k-structure, k fixed: 12 <= r < 12 + P -> 250 <= h -> Dom (F r h yfix)
      other nodes:          12 <= r < 12 + P -> 250 <= h -> Dom (F r h)
(250 <= h  <=>  M >= 500 for both parities.)  rocq/F/dom.json describes every constructor for the closure generator.
usage: genF.py
"""
import os, json
import rocqgen as RG
import nodeform as NF

OUT = RG.ROOT + 'rocq/F/'
os.makedirs(OUT, exist_ok=True)
HMIN = 250


def expr(const, coef, names=('N', 'h', 'y')):
    terms = [nm if c == 1 else '%d * %s' % (c, nm) for c, nm in zip(coef, names) if c]
    s = ' + '.join(terms) or '0'
    return '%s + %d' % (s, const) if const > 0 else ('%s - %d' % (s, -const) if const < 0 else s)


def fdef(node, par):
    toks, vals = node.form(par)
    args = [expr(*vals[t[1]]) for t in toks if t[0] == 'var']
    ps = 'N h y' if node.fam else 'N h'
    return 'Definition F_%s_%d %s : Q * tape := %s %s.' % (node.tag, par, ps, node.name(par), ' '.join('(%s)' % a for a in args))


if __name__ == '__main__':
    nodes_idx = json.load(open(RG.ROOT + 'rocq/N/nodes.json'))
    keys = sorted({v['key'] for v in nodes_idx.values()})
    f = ['(* generated by rocq/genF.py *)', 'From BusyCoq Require Import Individual62.', 'From BB6N Require Import Nodes.', 'Open Scope list.', '']
    for key in keys:
        node = NF.Node(key)
        for par in (0, 1):
            f.append(fdef(node, par))
    # aliases: partial and covered nodes have the same node form as their family
    f.append('')
    nal = 0
    for key in keys:
        ni = NF.P['nodes'].get(key, {})
        fam = ni.get('partial_of') or ni.get('covered_by')
        if not fam or fam not in NF.S: continue
        a, b = NF.Node(key), NF.Node(fam)
        for par in (0, 1):
            if a.form(par)[0] != b.form(par)[0]: continue
            n = sum(1 for t in a.form(par)[0] if t[0] == 'var')
            zs = ' '.join('z%d' % i for i in range(n))
            f += ['Lemma alias_%s_%d %s : %s %s = %s %s.' % (a.tag, par, zs, a.name(par), zs, b.name(par), zs),
                  'Proof. reflexivity. Qed.']
            nal += 1
    open(OUT + 'F.v', 'w').write('\n'.join(f) + '\n')
    print('aliases', nal)

    reach = json.load(open(RG.ROOT + 'rocq/reach.json'))
    d = ['(* generated by rocq/genF.py: the domain of the induction *)', 'From BusyCoq Require Import Individual62.',
         'From BB6F Require Import F.', 'Require Import Lia.', 'Open Scope list.', '',
         'Inductive Dom : Q * tape -> Prop :=']
    dom = {}
    for key in reach:
        node = NF.Node(key)
        ni = NF.P['nodes'][key]
        Pp = ni['P']
        for par in (0, 1):
            c = 'dom_%s_%d' % (node.tag, par)
            Fn = 'F_%s_%d' % (node.tag, par)
            if node.family_key:
                kf = ni['K_fam']; kmin = kf + ((node.kp - kf) % 2); yf = (kmin - node.kp) // 2
                d.append('  | %s r h y : 12 <= r < %d -> %d <= h -> %d <= y -> Dom (%s r h y)' % (c, 12 + Pp, HMIN, yf, Fn))
                dom[c] = dict(key=key, par=par, kind='family', P=Pp, yf=yf)
            elif node.fam:
                yfix = (node.kfix - node.kp) // 2
                d.append('  | %s r h : 12 <= r < %d -> %d <= h -> Dom (%s r h %d)' % (c, 12 + Pp, HMIN, Fn, yfix))
                dom[c] = dict(key=key, par=par, kind='kfixed', P=Pp, yfix=yfix)
            else:
                d.append('  | %s r h : 12 <= r < %d -> %d <= h -> Dom (%s r h)' % (c, 12 + Pp, HMIN, Fn))
                dom[c] = dict(key=key, par=par, kind='plain', P=Pp)
    # exceptional states (genExc.py): constant r and h below the domain, k free
    excf = RG.ROOT + 'rocq/F/exc.json'
    for e in (json.load(open(excf)) if os.path.exists(excf) else []):
        d.append('  | %s y : %d <= y -> Dom (F_%s_%d %d %d y)' % (e['ctor'], e['ymin'], NF.tagof(e['key']), e['par'], e['r'], e['h']))
    d[-1] += '.'
    open(OUT + 'Dom.v', 'w').write('\n'.join(d) + '\n')
    json.dump(dom, open(OUT + 'dom.json', 'w'), indent=1)
    print('F definitions %d, Dom constructors %d' % (2 * len(keys), len(dom)))
